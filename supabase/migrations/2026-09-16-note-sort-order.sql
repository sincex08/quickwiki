-- ============================================================
-- 笔记手动顺序（sort_order）
-- 在 Supabase 控制台 SQL Editor 执行一次即可（幂等，可重复执行）。
-- ============================================================
-- 语义：同容器（同一笔记本或未分类）内越小越靠前，步长 1024，便于两值之间插入。
--   * 全部为 null 的容器 = 未手动排序，客户端仍按 置顶 + 更新时间倒序
--   * 客户端写入、参与乐观锁；服务端不解释该字段，只负责存取
--   * 无需索引：顺序在客户端按容器在内存排序，服务端仅按 server_updated_at 增量拉取
-- ============================================================

alter table public.notes
  add column if not exists sort_order double precision;
